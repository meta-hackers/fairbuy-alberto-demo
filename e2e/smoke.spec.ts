import { expect, test, type Page } from '@playwright/test'

async function runSearch(page: Page) {
  await page.goto('/')
  await expect(page.getByRole('heading', { level: 1 })).toContainText('Cerco un PC gaming nuovo')
  await page.getByTestId('prepare-brief').click()
  await page.getByTestId('start-search').click()
  await expect(page.getByTestId('product-card-nova')).toBeVisible()
  await expect(page.getByTestId('product-card-strix')).toBeVisible({ timeout: 12_000 })
}

test('guided journey: ask, brief, discover, dismiss, undo, hard/soft, sellers, compare', async ({ page }) => {
  await runSearch(page)
  await expect(page.getByTestId('tier-nova')).toContainText('Match forte')
  await expect(page.getByTestId('tier-orbit')).toContainText('Compromesso preferenze')
  await expect(page.getByTestId('price-nova')).toContainText('1')
  await page.screenshot({ path: 'artifacts/screenshots/desktop-discovery.png', fullPage: true })

  await page.getByTestId('dismiss-orbit').click()
  await expect(page.getByTestId('dismiss-modal')).toBeVisible()
  await page.getByRole('button', { name: /RAM insufficiente/ }).click()
  await expect(page.getByText(/32 GB di RAM obbligatori o solo preferiti/)).toBeVisible()
  await page.getByLabel('Solo una preferenza').check()
  await page.getByTestId('dismiss-apply').click()
  await expect(page.getByTestId('product-card-vega')).toBeVisible()
  await expect(page.getByTestId('product-card-orbit')).toHaveCount(0)
  await expect(page.getByText('RAM 32 GB preferita').first()).toBeVisible()

  await page.getByRole('button', { name: 'Annulla' }).click()
  await expect(page.getByTestId('product-card-orbit')).toBeVisible()
  await expect(page.getByTestId('product-card-vega')).toHaveCount(0)

  const gpuModes = page.getByRole('group', { name: 'GPU: obbligatorio o preferito' })
  await gpuModes.getByRole('button', { name: 'Obbligatorio' }).click()
  await expect(page.getByTestId('tier-orbit')).toContainText('Conflitto obbligatorio')
  await gpuModes.getByRole('button', { name: 'Preferito' }).click()
  await expect(page.getByTestId('tier-orbit')).toContainText('Compromesso preferenze')

  const ramModes = page.getByRole('group', { name: 'RAM: obbligatorio o preferito' })
  await ramModes.getByRole('button', { name: 'Obbligatorio' }).click()
  await expect(page.getByTestId('tier-strix')).toContainText('Conflitto obbligatorio')
  await ramModes.getByRole('button', { name: 'Preferito' }).click()

  const novaCard = page.getByTestId('product-card-nova')
  await novaCard.getByRole('checkbox').check()
  await page.getByTestId('product-card-orbit').getByRole('checkbox').check()
  await page.getByTestId('open-compare').click()
  await expect(page.getByTestId('compare-modal')).toBeVisible()
  await expect(page.getByTestId('compare-modal')).toContainText('NOVA Forge 4070 SUPER')
  await page.getByRole('button', { name: 'Chiudi confronto' }).click()

  await novaCard.getByRole('button', { name: /Vedi offerte esatte/ }).click()
  await expect(page.getByTestId('seller-view')).toBeVisible()
  await page.screenshot({ path: 'artifacts/screenshots/desktop-seller-offers.png', fullPage: true })
  const rows = page.locator('[data-testid^="seller-nova-"]')
  await expect(rows.first()).toContainText('Galaxus')
  await expect(rows.first()).toContainText(/1.899/)
  await expect(rows.nth(1)).toContainText('MediaWorld')
  await expect(page.getByTestId('seller-unknown-nova-p')).toBeVisible()
  await page.getByRole('button', { name: /Dettaglio retailer/ }).first().click()
  await expect(page.getByRole('dialog')).toContainText('Nessun acquisto effettuato')
  await page.locator('.outbound-modal').getByRole('button', { name: 'Chiudi' }).click()
})

test('dismissal can be skipped and undone without learning a preference', async ({ page }) => {
  await runSearch(page)
  await page.getByTestId('dismiss-strix').click()
  await page.getByTestId('dismiss-skip').click()
  await expect(page.getByTestId('product-card-strix')).toHaveCount(0)
  await expect(page.getByText('Nessuna preferenza appresa')).toBeVisible()
  await page.getByRole('button', { name: 'Annulla' }).click()
  await expect(page.getByTestId('product-card-strix')).toBeVisible()
})

test('source failure shows a partial ranking and recovery restores it', async ({ page }) => {
  await runSearch(page)
  await expect(page.getByTestId('price-nova')).toContainText(/1.899/)
  await page.getByTestId('source-toggle').click()
  await expect(page.getByTestId('source-banner').first()).toContainText('parziale')
  await expect(page.getByTestId('price-nova')).not.toContainText(/1.899/)
  await expect(page.getByTestId('tier-vortex')).toContainText('Conflitto obbligatorio')
  await page.screenshot({ path: 'artifacts/screenshots/desktop-source-offline.png', fullPage: true })
  await page.getByTestId('source-toggle').click()
  await expect(page.getByTestId('source-banner')).toHaveCount(0)
  await expect(page.getByTestId('price-nova')).toContainText(/1.899/)
  await expect(page.getByTestId('tier-vortex')).toContainText('Dati insufficienti')
})

test('favorites persist in localStorage and reset clears the demo', async ({ page }) => {
  await runSearch(page)
  await page.getByTestId('favorite-nova').click()
  const stored = await page.evaluate(() => localStorage.getItem('fairbuy-demo-favorites-v1'))
  expect(stored).toContain('nova')
  await page.reload()
  await expect(page.getByRole('button', { name: /Preferiti \(1\)/ })).toBeVisible()
  await page.getByTestId('reset-demo').click()
  await expect(page.getByRole('button', { name: /Preferiti \(0\)/ })).toBeVisible()
  const cleared = await page.evaluate(() => localStorage.getItem('fairbuy-demo-favorites-v1'))
  expect(cleared).toBe('[]')
})

test('empty state explains a filter with no matches and can be cleared', async ({ page }) => {
  await runSearch(page)
  await page.getByTestId('favorites-filter').check()
  await expect(page.getByTestId('empty-state')).toBeVisible()
  await expect(page.getByTestId('empty-state')).toContainText('Nessun preferito')
  await page.getByRole('button', { name: 'Mostra tutti i prodotti' }).click()
  await expect(page.getByTestId('empty-state')).toHaveCount(0)
})

test('mobile viewport has no horizontal overflow and navigation is reachable', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await runSearch(page)
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth)
  expect(overflow).toBeLessThanOrEqual(1)
  await expect(page.getByTestId('product-card-nova')).toBeVisible()
  await page.getByRole('button', { name: 'Apri navigazione' }).click()
  await expect(page.locator('.app-rail')).toHaveClass(/is-open/)
  await page.screenshot({ path: 'artifacts/screenshots/mobile-discovery.png', fullPage: true })
})
